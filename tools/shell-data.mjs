// Catalogue / site-config handling for sync-shell: validation, generated JS data files, money(), <!-- gen: NAME --> regions.
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const TOOLS = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(TOOLS, '..');
const readJson = (f) => JSON.parse(readFileSync(path.join(TOOLS, f), 'utf8'));
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
const publicOnly = (o) => Object.fromEntries(Object.entries(o).filter(([k]) => !k.startsWith('_')));

const catalogue = readJson('catalogue.json');
const siteConfig = readJson('site-config.json');
export const publicCatalogue = publicOnly(catalogue);
export const publicConfig = publicOnly(siteConfig);

// ---- validation ----
export const dataErrors = [];
{
  const slugs = (list) => new Set((list ?? []).map((x) => x.slug));
  const occ = slugs(catalogue.occasions), rec = slugs(catalogue.recipients);
  const seen = new Set(), pkgs = new Set();
  for (const h of catalogue.hampers ?? []) {
    const w = `catalogue.json hamper "${h.slug}"`;
    if (seen.has(h.slug)) dataErrors.push(`${w}: duplicate slug`);
    seen.add(h.slug);
    if (!/^P\d{2,}$/.test(h.package ?? '')) dataErrors.push(`${w}: package must look like P01`);
    if (pkgs.has(h.package)) dataErrors.push(`${w}: duplicate package ${h.package}`);
    pkgs.add(h.package);
    if (!Number.isInteger(h.price) || h.price < 0) dataErrors.push(`${w}: price must be whole rupees`);
    for (const o of h.occasions ?? []) if (!occ.has(o)) dataErrors.push(`${w}: unknown occasion "${o}"`);
    for (const r of h.recipients ?? []) if (!rec.has(r)) dataErrors.push(`${w}: unknown recipient "${r}"`);
  }
  // occasion icons must exist in the sprite (placeholder imagery until photography exists)
  const spriteIds = new Set([...readFileSync(path.join(ROOT, 'html/assets/icons/sprite.svg'), 'utf8').matchAll(/<symbol id="([^"]+)"/g)].map((m) => m[1]));
  for (const o of catalogue.occasions ?? []) {
    if (o.icon && !spriteIds.has(o.icon)) dataErrors.push(`occasion "${o.slug}": icon "${o.icon}" is not in html/assets/icons/sprite.svg`);
  }
  for (const a of catalogue.addons ?? []) {
    if (!Number.isInteger(a.price) || a.price < 0) dataErrors.push(`add-on "${a.slug}": price must be whole rupees`);
  }
}

// ---- generated data files (absolute path -> content) ----
const banner = (src) => `/* GENERATED by tools/sync-shell.mjs from tools/${src}. Do not edit by hand. */\n`;
export const generatedFiles = new Map([
  [path.join(ROOT, 'html/assets/js/catalogue-data.js'), banner('catalogue.json') + 'window.BOXTOP_CATALOGUE = ' + JSON.stringify(publicCatalogue, null, 2) + ';\n'],
  [path.join(ROOT, 'html/assets/js/site-config.js'), banner('site-config.json') + 'window.BOXTOP_CONFIG = ' + JSON.stringify(publicConfig, null, 2) + ';\n'],
]);

// The browser's own money(): generated markup can never format a price differently from the pages.
const money = (() => {
  const win = { BOXTOP_CONFIG: publicConfig };
  new Function('window', readFileSync(path.join(ROOT, 'html/assets/js/format.js'), 'utf8'))(win);
  return win.money;
})();

// ---- gen regions ----
function hamperCard(h, root) {
  const tone = String(h.image ?? '').replace(/^placeholder:/, '');
  const badge = h.oos ? '<span class="pv-badge pv-badge--oos">Sold out</span>'
    : h.new ? '<span class="pv-badge">New</span>'
    : h.featured ? '<span class="pv-badge">Featured</span>' : '';
  return [
    `<div class="pv-card${h.oos ? ' pv-card--oos' : ''}" data-package="${esc(h.package)}">`,
    badge && `  ${badge}`,
    `  <div class="pv-thumb" data-placeholder="${esc(tone)}"><svg class="icon" aria-hidden="true"><use href="#i-gift"/></svg></div>`,
    !h.oos && `  <button type="button" class="pv-quickadd" data-quickadd="${esc(h.slug)}">+ Quick add</button>`,
    '  <div class="pv-info">',
    h.contents?.length && `    <small class="pv-meta">${esc(h.contents.slice(0, 2).join(', '))}</small>`,
    // every hamper links to the one sample detail page until the catalogue-driven prompts
    `    <p class="pv-name"><a href="${root}box/sample-hamper.html">${esc(h.name)}</a></p>`,
    `    <div class="pv-row"><span class="pv-price">${money(h.price)}</span></div>`,
    '  </div>',
    '</div>',
  ].filter(Boolean).join('\n');
}
// every occasion links to the one sample occasion page until the catalogue-driven prompts
const occasionCard = (o, root) => [
  `<a class="pv-card pv-card--occasion" href="${root}occasion/sample-occasion.html" data-occasion="${esc(o.slug)}">`,
  `  <div class="pv-thumb" data-placeholder="${esc(o.slug)}"><svg class="icon" aria-hidden="true"><use href="#${esc(o.icon ?? 'i-gift')}"/></svg></div>`,
  `  <div class="pv-info"><p class="pv-name">${esc(o.name)}</p></div>`,
  '</a>',
].join('\n');
const featuredFirst = (list) => [...list].sort((a, b) => Number(b.featured) - Number(a.featured));
const nameList = (list) => (list ?? []).map((x) => `<li data-slug="${esc(x.slug)}">${esc(x.name)}</li>`).join('\n');

const GENERATORS = {
  'hamper-preview': ({ root }) => featuredFirst((catalogue.hampers ?? []).filter((h) => !h.oos)).slice(0, 3).map((h) => hamperCard(h, root)).join('\n'),
  'hamper-featured': ({ root }) => (catalogue.hampers ?? []).filter((h) => h.featured && !h.oos).map((h) => hamperCard(h, root)).join('\n'),
  'occasion-cards': ({ root }) => (catalogue.occasions ?? []).map((o) => occasionCard(o, root)).join('\n'),
  'hampers-all': ({ root }) => (catalogue.hampers ?? []).map((h) => hamperCard(h, root)).join('\n'),
  'occasion-list': () => nameList(catalogue.occasions),
  'recipient-list': () => nameList(catalogue.recipients),
  'addon-list': () => (catalogue.addons ?? []).map((a) => `<li data-slug="${esc(a.slug)}">${esc(a.name)} <span>${a.price ? money(a.price) : 'Free'}</span></li>`).join('\n'),
};

export function fillGen(html, ctx, pagePath) {
  return html.replace(/<!-- gen: ([\w-]+) -->[\s\S]*?<!-- \/gen: \1 -->/g, (m, name) => {
    const g = GENERATORS[name];
    if (!g) throw new Error(`${pagePath}: unknown gen region "${name}" (known: ${Object.keys(GENERATORS).join(', ')})`);
    const body = g(ctx);
    return `<!-- gen: ${name} -->\n${body ? body + '\n' : ''}<!-- /gen: ${name} -->`;
  });
}
