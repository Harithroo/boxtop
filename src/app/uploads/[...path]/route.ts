// Serves uploaded images from UPLOAD_DIR at /uploads/<folder>/<file>.
// saveImage() has always returned these addresses; this is what answers them.
import { readFile } from "node:fs/promises";
import path from "node:path";
import type { NextRequest } from "next/server";
import { ADMIN_COOKIE, verifyToken } from "@/lib/auth";
import { PRIVATE_UPLOADS, PUBLIC_UPLOADS, UPLOAD_DIR } from "@/lib/upload-dir";

const TYPES: Record<string, string> = { ".webp": "image/webp", ".jpg": "image/jpeg", ".jpeg": "image/jpeg", ".png": "image/png", ".avif": "image/avif" };
const notFound = () => new Response("Not found", { status: 404 });

export async function GET(req: NextRequest, { params }: { params: Promise<{ path: string[] }> }) {
  const parts = (await params).path;
  if (parts.length !== 2) return notFound();
  const [folder, file] = parts;
  const type = TYPES[path.extname(file).toLowerCase()];
  // file names are generated by saveImage(): letters, digits, dashes and one extension
  if (!type || !/^[a-z0-9-]+\.[a-z0-9]+$/i.test(file)) return notFound();

  const isPrivate = PRIVATE_UPLOADS.has(folder);
  if (!isPrivate && !PUBLIC_UPLOADS.has(folder)) return notFound();
  // a missing session answers 404, not 401, so a private address doesn't reveal that it exists
  if (isPrivate && !(await verifyToken(req.cookies.get(ADMIN_COOKIE)?.value))) return notFound();

  const full = path.join(/* turbopackIgnore: true */ UPLOAD_DIR, folder, file);
  if (!full.startsWith(UPLOAD_DIR + path.sep)) return notFound();
  try {
    const body = await readFile(full);
    return new Response(new Uint8Array(body), {
      headers: {
        "Content-Type": type,
        "Content-Length": String(body.byteLength),
        // names are random and never reused, so a public file can be cached for good
        "Cache-Control": isPrivate ? "private, no-store" : "public, max-age=31536000, immutable",
        "X-Content-Type-Options": "nosniff",
      },
    });
  } catch {
    return notFound();
  }
}
